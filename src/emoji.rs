//! Emoji support for rich-rs.
//!
//! This module provides emoji lookup and replacement functionality.
//! Emoji names are mapped to their Unicode characters using a compile-time
//! perfect hash map for efficient lookups.

use once_cell::sync::Lazy;
use phf::phf_map;
use regex::Regex;

use crate::error::{ParseError, Result};
use crate::style::Style;

/// Emoji variant selector.
///
/// Controls how the emoji is displayed:
/// - `Text` - Display as text-style (monochrome) using U+FE0E
/// - `Emoji` - Display as emoji-style (colored) using U+FE0F
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub enum EmojiVariant {
    /// Text presentation selector (U+FE0E)
    Text,
    /// Emoji presentation selector (U+FE0F)
    #[default]
    Emoji,
}

impl EmojiVariant {
    /// Get the variant selector character.
    pub fn selector(&self) -> &'static str {
        match self {
            EmojiVariant::Text => "\u{fe0e}",
            EmojiVariant::Emoji => "\u{fe0f}",
        }
    }
}

/// A single emoji character.
///
/// # Example
///
/// ```
/// use rich_rs::Emoji;
///
/// let emoji = Emoji::new("smile").unwrap();
/// assert_eq!(emoji.to_string(), "\u{1f604}");
/// ```
#[derive(Debug, Clone)]
pub struct Emoji {
    /// The emoji name.
    pub name: String,
    /// Optional style for rendering.
    pub style: Option<Style>,
    /// Optional variant selector.
    pub variant: Option<EmojiVariant>,
    /// The emoji character(s).
    char: String,
}

impl Emoji {
    /// Create a new Emoji from its name.
    ///
    /// # Arguments
    ///
    /// * `name` - The emoji name (e.g., "smile", "thumbs_up")
    ///
    /// # Errors
    ///
    /// Returns `ParseError::NoEmoji` if no emoji with that name exists.
    pub fn new(name: &str) -> Result<Self> {
        Self::with_style(name, None, None)
    }

    /// Create a new Emoji with style and variant.
    ///
    /// # Arguments
    ///
    /// * `name` - The emoji name
    /// * `style` - Optional style for rendering
    /// * `variant` - Optional variant selector
    pub fn with_style(
        name: &str,
        style: Option<Style>,
        variant: Option<EmojiVariant>,
    ) -> Result<Self> {
        let name_lower = name.to_lowercase();
        let base_char = EMOJI
            .get(&name_lower)
            .ok_or_else(|| ParseError::no_emoji(name))?;

        // Only append variant selector if the base emoji doesn't already have one
        let char = if let Some(v) = variant {
            if base_char.ends_with('\u{fe0e}') || base_char.ends_with('\u{fe0f}') {
                // Already has a variant selector, don't duplicate
                base_char.to_string()
            } else {
                format!("{}{}", base_char, v.selector())
            }
        } else {
            base_char.to_string()
        };

        Ok(Self {
            name: name_lower,
            style,
            variant,
            char,
        })
    }

    /// Replace emoji codes in text with emoji characters.
    ///
    /// Emoji codes are in the format `:name:` or `:name-variant:` where
    /// variant is either "emoji" or "text".
    ///
    /// # Example
    ///
    /// ```
    /// use rich_rs::Emoji;
    ///
    /// let text = Emoji::replace("Hello :smile:!");
    /// assert_eq!(text, "Hello \u{1f604}!");
    ///
    /// let text = Emoji::replace(":+1: Great!");
    /// assert_eq!(text, "\u{1f44d} Great!");
    /// ```
    pub fn replace(text: &str) -> String {
        // Pattern uses [^:\s] to exclude colons from emoji names,
        // preventing matches across internal colons like `:a:b:`
        static EMOJI_RE: Lazy<Regex> =
            Lazy::new(|| Regex::new(r":([^:\s]*?)(?:(?:-)(emoji|text))?:").unwrap());

        EMOJI_RE
            .replace_all(text, |caps: &regex::Captures| {
                let full_match = caps.get(0).unwrap().as_str();
                let name = caps.get(1).map(|m| m.as_str().to_lowercase());
                let variant = caps.get(2).map(|m| m.as_str());

                if let Some(name) = name
                    && let Some(emoji_char) = EMOJI.get(name.as_str())
                {
                    // Only append variant selector if emoji doesn't already have one
                    let has_selector =
                        emoji_char.ends_with('\u{fe0e}') || emoji_char.ends_with('\u{fe0f}');
                    let variant_selector = if has_selector {
                        "" // Don't duplicate existing selector
                    } else {
                        match variant {
                            Some("text") => "\u{fe0e}",
                            Some("emoji") => "\u{fe0f}",
                            _ => "",
                        }
                    };
                    return format!("{}{}", emoji_char, variant_selector);
                }
                // If not found, return the original text
                full_match.to_string()
            })
            .into_owned()
    }

    /// Get the emoji character.
    pub fn as_str(&self) -> &str {
        &self.char
    }
}

impl std::fmt::Display for Emoji {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        write!(f, "{}", self.char)
    }
}

