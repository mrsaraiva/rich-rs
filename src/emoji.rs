#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_basic_lookup() {
        let emoji = Emoji::new("smile").unwrap();
        assert_eq!(emoji.to_string(), "\u{1f604}");
    }

    #[test]
    fn test_replace_multiple_emoji() {
        let text = Emoji::replace("Hello :smile: and :+1:!");
        assert_eq!(text, "Hello \u{1f604} and \u{1f44d}!");
    }

    #[test]
    fn test_invalid_emoji_name() {
        let result = Emoji::new("not_a_real_emoji_xyz");
        assert!(result.is_err());
        if let Err(ParseError::NoEmoji(name)) = result {
            assert_eq!(name, "not_a_real_emoji_xyz");
        } else {
            panic!("Expected NoEmoji error");
        }
    }

    #[test]
    fn test_variant_handling() {
        // Test with emoji variant
        let emoji = Emoji::with_style("smile", None, Some(EmojiVariant::Emoji)).unwrap();
        assert!(emoji.to_string().ends_with("\u{fe0f}"));

        // Test with text variant
        let emoji = Emoji::with_style("smile", None, Some(EmojiVariant::Text)).unwrap();
        assert!(emoji.to_string().ends_with("\u{fe0e}"));

        // Test replace with variants
        let text = Emoji::replace(":smile-emoji:");
        assert!(text.ends_with("\u{fe0f}"));

        let text = Emoji::replace(":smile-text:");
        assert!(text.ends_with("\u{fe0e}"));
    }

    #[test]
    fn test_case_insensitivity() {
        // Names should be case-insensitive
        let emoji1 = Emoji::new("smile").unwrap();
        let emoji2 = Emoji::new("SMILE").unwrap();
        let emoji3 = Emoji::new("Smile").unwrap();

        assert_eq!(emoji1.to_string(), emoji2.to_string());
        assert_eq!(emoji2.to_string(), emoji3.to_string());
    }

    #[test]
    fn test_replace_preserves_unknown() {
        // Unknown emoji codes should be preserved
        let text = Emoji::replace("Hello :unknown_emoji_xyz: world");
        assert_eq!(text, "Hello :unknown_emoji_xyz: world");
    }

    #[test]
    fn test_replace_adjacent_colons() {
        // Adjacent emoji codes should be handled correctly, not matched across colons
        let text = Emoji::replace(":smile::+1:");
        assert_eq!(text, "\u{1f604}\u{1f44d}");

        // :a: is valid (blood type A), so ":a:b:" should become "🅰b:"
        let text = Emoji::replace(":a:b:");
        assert_eq!(text, "\u{1f170}b:");

        // Ensure we don't match "a:b" as an emoji name
        let text = Emoji::replace(":nonexistent:colon:test:");
        // None of these are valid emoji, so should be preserved as-is
        assert_eq!(text, ":nonexistent:colon:test:");
    }

    #[test]
    fn test_emoji_map_size() {
        // Verify we have a reasonable number of emojis
        assert!(EMOJI.len() > 3000);
    }

    #[test]
    fn test_thumbs_up() {
        assert!(EMOJI.get("+1").is_some());
        assert!(EMOJI.get("thumbsup").is_some());
    }
}
